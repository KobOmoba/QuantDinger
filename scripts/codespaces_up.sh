#!/usr/bin/env bash
# Start QuantDinger in GitHub Codespaces (or any host) without a project .env.
#
# Why: the backend entrypoint chowns the bind-mounted /app/.env to UID 10001
# and sets mode 600, so on Codespaces the host user loses read access to .env
# and Compose / the migration container fail with "permission denied".
#
# This script never reads or mounts .env. On first run it writes
# docker-compose.codespaces.yml (git-ignored) with freshly generated secrets
# hardcoded into the services' environment, then starts the stack with
# `--env-file /dev/null` so Compose does not look for .env either.
# Later runs reuse the same file, so the database password and keys stay stable.
#
# Usage:  bash scripts/codespaces_up.sh            # build and start everything
#         bash scripts/codespaces_up.sh down       # any other compose command
set -euo pipefail
cd "$(dirname "$0")/.."

GENERATED=docker-compose.codespaces.yml

rand_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$1"
  else
    python3 -c "import secrets, sys; print(secrets.token_hex(int(sys.argv[1])))" "$1"
  fi
}

if [ ! -f "$GENERATED" ]; then
  pg_password=$(rand_hex 18)
  secret_key=$(rand_hex 32)
  credential_key=$(rand_hex 32)
  admin_password=$(rand_hex 8)

  # The backend asks Docker for 65535 open files; some hosts cap the hard limit
  # lower, and then the container fails with "error setting rlimits".
  nofile=65535
  host_nofile=$(ulimit -Hn)
  if [ "$host_nofile" != "unlimited" ] && [ "$host_nofile" -lt "$nofile" ]; then
    nofile=$host_nofile
  fi

  if [ -n "${CODESPACE_NAME:-}" ] && [ -n "${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:-}" ]; then
    base="https://${CODESPACE_NAME}"
    domain="${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN}"
    frontend_url="${base}-8888.${domain},${base}-8889.${domain}"
  else
    frontend_url="http://localhost:8888,http://localhost:8889"
  fi

  umask 077
  cat > "$GENERATED" <<EOF
# Generated by scripts/codespaces_up.sh. Contains secrets: do not commit.
# Delete this file (and run 'docker compose down -v') to start over with new secrets.
x-qd-env: &qd-env
  POSTGRES_PASSWORD: "${pg_password}"
  DATABASE_URL: "postgresql://quantdinger:${pg_password}@postgres:5432/quantdinger"
  SECRET_KEY: "${secret_key}"
  CREDENTIAL_ENCRYPTION_KEY: "${credential_key}"
  ADMIN_USER: "quantdinger"
  ADMIN_PASSWORD: "${admin_password}"
  FRONTEND_HOST: "0.0.0.0"
  MOBILE_HOST: "0.0.0.0"
  FRONTEND_URL: "${frontend_url}"
  # Settings saved from the admin panel persist in the backend_data volume
  # instead of the host .env.
  QUANTDINGER_ENV_FILE: "/app/data/quantdinger.env"

# /dev/null replaces the ./.env bind mount, so no container touches the host file.
x-qd-volumes: &qd-volumes
  - backend_data:/app/data
  - /dev/null:/app/.env

services:
  env-sync:
    entrypoint: ["python", "-c", "print('env-sync skipped: Codespaces setup does not use .env')"]
  postgres:
    environment:
      POSTGRES_PASSWORD: "${pg_password}"
  kafka-init: {environment: *qd-env, volumes: *qd-volumes}
  migration: {environment: *qd-env, volumes: *qd-volumes}
  backend:
    environment: *qd-env
    volumes: *qd-volumes
    ulimits:
      nofile: {soft: ${nofile}, hard: ${nofile}}
  trading-worker: {environment: *qd-env, volumes: *qd-volumes}
  kafka-audit-worker: {environment: *qd-env, volumes: *qd-volumes}
  strategy-dispatcher-worker: {environment: *qd-env, volumes: *qd-volumes}
  strategy-evaluator-worker: {environment: *qd-env, volumes: *qd-volumes}
  scheduler-worker: {environment: *qd-env, volumes: *qd-volumes}
  celery-worker: {environment: *qd-env, volumes: *qd-volumes}
  celery-beat: {environment: *qd-env, volumes: *qd-volumes}
EOF
  echo "Created $GENERATED with new secrets."
  echo "Admin login: quantdinger / ${admin_password}"
  echo "(Also stored as ADMIN_PASSWORD in $GENERATED.)"
fi

# Compose substitutes these into the base file's \${...} references (database
# URL and published port bindings), so take them from the generated file.
read_value() {
  sed -n "s/^  $1: \"\(.*\)\"$/\1/p" "$GENERATED" | head -n 1
}
export POSTGRES_PASSWORD; POSTGRES_PASSWORD=$(read_value POSTGRES_PASSWORD)
export FRONTEND_HOST; FRONTEND_HOST=$(read_value FRONTEND_HOST)
export MOBILE_HOST; MOBILE_HOST=$(read_value MOBILE_HOST)
export FRONTEND_URL; FRONTEND_URL=$(read_value FRONTEND_URL)
# The base file defaults to a mainland-China Docker Hub mirror for the backend
# build; Codespaces runners reach the official image directly.
export PYTHON_BASE_IMAGE="${PYTHON_BASE_IMAGE:-python:3.12-slim-bookworm}"

files=(-f docker-compose.yml -f "$GENERATED")
# Keep the optional local override (for example the Groq key pass-through).
if [ -f docker-compose.override.yml ]; then
  files+=(-f docker-compose.override.yml)
fi

if [ "$#" -eq 0 ]; then
  set -- up -d --build
fi
exec docker compose --env-file /dev/null "${files[@]}" "$@"
